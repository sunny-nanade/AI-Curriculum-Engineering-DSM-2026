# Cell 3: Theory - Undamped SDOF
notebook["cells"].append({
    "cell_type": "markdown",
    "metadata": {},
    "source": [
        "---\n",
        "## Part A: Undamped Free Vibrations ($\\zeta = 0$)\n",
        "\n",
        "### System: Mass-Spring\n",
        "\n",
        "**Equation of motion**:\n",
        "$$m\\ddot{x} + kx = 0$$\n",
        "\n",
        "Divide by $m$:\n",
        "$$\\ddot{x} + \\omega_n^2 x = 0, \\quad \\omega_n = \\sqrt{\\frac{k}{m}}$$\n",
        "\n",
        "### Solution\n",
        "\n",
        "**General solution** (assume $x = e^{\\lambda t}$):\n",
        "$$\\lambda^2 + \\omega_n^2 = 0 \\quad \\Rightarrow \\quad \\lambda = \\pm i\\omega_n$$\n",
        "\n",
        "Real form:\n",
        "$$x(t) = A\\cos(\\omega_n t) + B\\sin(\\omega_n t)$$\n",
        "\n",
        "Or in amplitude-phase form:\n",
        "$$x(t) = X_0\\cos(\\omega_n t - \\phi)$$\n",
        "\n",
        "where:\n",
        "- $X_0 = \\sqrt{A^2 + B^2}$ → amplitude\n",
        "- $\\phi = \\arctan(B/A)$ → phase angle\n",
        "\n",
        "### Initial Conditions\n",
        "\n",
        "Given $x(0) = x_0$ and $\\dot{x}(0) = v_0$:\n",
        "$$A = x_0, \\quad B = \\frac{v_0}{\\omega_n}$$\n",
        "\n",
        "Therefore:\n",
        "$$x(t) = x_0\\cos(\\omega_n t) + \\frac{v_0}{\\omega_n}\\sin(\\omega_n t)$$\n",
        "\n",
        "### Key Properties\n",
        "\n",
        "**Frequency**:\n",
        "- Independent of amplitude (linear system)\n",
        "- Depends only on $k$ and $m$\n",
        "- $\\omega_n \\uparrow$ when $k \\uparrow$ (stiffer) or $m \\downarrow$ (lighter)\n",
        "\n",
        "**Period**: $T_n = \\frac{2\\pi}{\\omega_n} = 2\\pi\\sqrt{\\frac{m}{k}}$\n",
        "\n",
        "**Energy**: Conserved!\n",
        "$$E = \\frac{1}{2}kX_0^2 = KE + PE$$\n",
        "\n",
        "**Phase portrait**: Perfect circle (energy level curve)\n",
        "\n",
        "---\n"
    ]
})

