# Cell 5: Theory - Damped SDOF
notebook["cells"].append({
    "cell_type": "markdown",
    "metadata": {},
    "source": [
        "---\n",
        "## Part B: Damped Free Vibrations ($\\zeta > 0$)\n",
        "\n",
        "### Equation with Damping\n",
        "\n",
        "$$m\\ddot{x} + c\\dot{x} + kx = 0$$\n",
        "\n",
        "Standard form:\n",
        "$$\\ddot{x} + 2\\zeta\\omega_n\\dot{x} + \\omega_n^2 x = 0$$\n",
        "\n",
        "where:\n",
        "- $\\omega_n = \\sqrt{k/m}$ → undamped natural frequency\n",
        "- $\\zeta = \\frac{c}{2\\sqrt{km}} = \\frac{c}{c_c}$ → damping ratio\n",
        "- $c_c = 2\\sqrt{km} = 2m\\omega_n$ → critical damping coefficient\n",
        "\n",
        "### Solution (assume $x = e^{\\lambda t}$)\n",
        "\n",
        "Characteristic equation:\n",
        "$$\\lambda^2 + 2\\zeta\\omega_n\\lambda + \\omega_n^2 = 0$$\n",
        "\n",
        "Roots:\n",
        "$$\\lambda = -\\zeta\\omega_n \\pm \\omega_n\\sqrt{\\zeta^2 - 1}$$\n",
        "\n",
        "### Three Cases\n",
        "\n",
        "#### 1. Underdamped ($\\zeta < 1$)\n",
        "\n",
        "**Roots**: Complex conjugates $\\lambda = -\\zeta\\omega_n \\pm i\\omega_d$\n",
        "\n",
        "where $\\omega_d = \\omega_n\\sqrt{1 - \\zeta^2}$ → **damped frequency**\n",
        "\n",
        "**Solution**:\n",
        "$$x(t) = X_0 e^{-\\zeta\\omega_n t}\\cos(\\omega_d t - \\phi)$$\n",
        "\n",
        "**Characteristics**:\n",
        "- Oscillates with **exponentially decaying envelope**\n",
        "- Frequency $\\omega_d < \\omega_n$ (damping slows oscillation)\n",
        "- **Logarithmic decrement**: $\\delta = \\ln\\frac{x_n}{x_{n+1}} = \\frac{2\\pi\\zeta}{\\sqrt{1-\\zeta^2}}$\n",
        "\n",
        "#### 2. Critically Damped ($\\zeta = 1$)\n",
        "\n",
        "**Roots**: Real, repeated $\\lambda = -\\omega_n$\n",
        "\n",
        "**Solution**:\n",
        "$$x(t) = (A + Bt)e^{-\\omega_n t}$$\n",
        "\n",
        "**Characteristics**:\n",
        "- **Fastest return** to equilibrium without overshoot\n",
        "- No oscillation\n",
        "- Used in: door closers, automotive dampers\n",
        "\n",
        "#### 3. Overdamped ($\\zeta > 1$)\n",
        "\n",
        "**Roots**: Real, distinct $\\lambda_1, \\lambda_2 < 0$\n",
        "\n",
        "**Solution**:\n",
        "$$x(t) = A e^{\\lambda_1 t} + B e^{\\lambda_2 t}$$\n",
        "\n",
        "**Characteristics**:\n",
        "- **Slow exponential decay**\n",
        "- No oscillation (over-damped)\n",
        "- Slower than critical damping\n",
        "\n",
        "### Logarithmic Decrement\n",
        "\n",
        "For underdamped systems, measure decay:\n",
        "\n",
        "$$\\delta = \\ln\\frac{x_n}{x_{n+1}} = \\frac{2\\pi\\zeta}{\\sqrt{1-\\zeta^2}} \\approx 2\\pi\\zeta \\quad (\\text{for } \\zeta \\ll 1)$$\n",
        "\n",
        "Invert to find damping:\n",
        "$$\\zeta = \\frac{\\delta}{\\sqrt{4\\pi^2 + \\delta^2}}$$\n",
        "\n",
        "**Experimental use**: Measure successive peak amplitudes to extract $\\zeta$!\n",
        "\n",
        "---\n"
    ]
})

