notebook["cells"].append({
    "cell_type": "markdown",
    "metadata": {},
    "source": [
        "---\n",
        "## Part B: Rolling Motion Analysis \n",
        "\n",
        "### Classic Problem: Rolling Down an Incline\n",
        "\n",
        "**Setup**: Object (mass m, radius R, moment of inertia I) rolls down incline (angle θ)\n",
        "\n",
        "**Forces**:\n",
        "- Weight: $mg$ (down)\n",
        "- Normal: $N$ (perpendicular to incline)\n",
        "- Friction: $f$ (up the incline) — **provides torque for rotation!**\n",
        "\n",
        "**Equations**:\n",
        "\n",
        "**Translation** (down incline, +x direction):\n",
        "$$m a_{cm} = mg \\sin\\theta - f$$\n",
        "\n",
        "**Rotation** (about center of mass):\n",
        "$$I \\alpha = f R$$\n",
        "\n",
        "**Rolling constraint** (no slip):\n",
        "$$a_{cm} = \\alpha R$$\n",
        "\n",
        "### Solution Strategy\n",
        "1. Use constraint to eliminate $\\alpha$: $\\alpha = a_{cm}/R$\n",
        "2. From rotation equation: $f = I \\alpha / R = I a_{cm} / R^2$\n",
        "3. Substitute into translation equation:\n",
        "   $$m a_{cm} = mg \\sin\\theta - \\frac{I a_{cm}}{R^2}$$\n",
        "4. Solve for $a_{cm}$:\n",
        "   $$\\boxed{a_{cm} = \\frac{g \\sin\\theta}{1 + I/(mR^2)}}$$\n",
        "\n",
        "### Key Results\n",
        "\n",
        "**Define**: $\\beta = I/(mR^2)$ (dimensionless shape factor)\n",
        "- Solid sphere: $\\beta = 2/5$\n",
        "- Solid disk: $\\beta = 1/2$\n",
        "- Hollow cylinder: $\\beta = 1$\n",
        "\n",
        "**Acceleration**:\n",
        "$$a_{cm} = \\frac{g \\sin\\theta}{1 + \\beta}$$\n",
        "\n",
        "**Who wins the race down the incline?**\n",
        "- **Smallest $\\beta$ → fastest** (less rotational inertia)\n",
        "- Order: Solid sphere > Solid disk > Hollow cylinder\n",
        "- **Independent of mass and radius!** (shape only)\n",
        "\n",
        "**Friction force**:\n",
        "$$f = \\frac{\\beta}{1 + \\beta} mg \\sin\\theta$$\n",
        "\n",
        "**No friction → no rotation** (would just slide with $a = g\\sin\\theta$, faster but no roll)\n",
        "\n",
        "---\n"
    ]
})

