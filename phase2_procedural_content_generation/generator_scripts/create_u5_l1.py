# Cell 3: Part A - Theory
notebook["cells"].append({
    "cell_type": "markdown",
    "metadata": {},
    "source": [
        "---\n",
        "## Part A: Rigid Body Equations of Motion \n",
        "\n",
        "### What is a Rigid Body?\n",
        "**Definition**: An extended object where distances between all points remain constant\n",
        "- **Idealization**: No deformation (perfectly stiff)\n",
        "- **Reality**: Steel beam, wheel, robot link → nearly rigid\n",
        "- **Not rigid**: Spring, rope, fluid\n",
        "\n",
        "### Two Types of Motion\n",
        "\n",
        "#### 1. Translation (ΣF = m·a_cm)\n",
        "Every point has the **same velocity**:\n",
        "$$\\mathbf{v}_P = \\mathbf{v}_{cm} \\quad \\text{(for all points P)}$$\n",
        "\n",
        "**Newton's 2nd Law for CM**:\n",
        "$$\\sum \\mathbf{F}_{\\text{external}} = m \\mathbf{a}_{cm}$$\n",
        "\n",
        "**Key insight**: Center of mass moves like a particle with total mass!\n",
        "\n",
        "#### 2. Rotation (Στ = I·α)\n",
        "Object spins about an axis. Each point has different velocity!\n",
        "\n",
        "**Velocity of point P on rigid body**:\n",
        "$$\\mathbf{v}_P = \\mathbf{v}_{cm} + \\boldsymbol{\\omega} \\times \\mathbf{r}_{P/cm}$$\n",
        "\n",
        "where:\n",
        "- $\\boldsymbol{\\omega}$ = angular velocity vector (rad/s)\n",
        "- $\\mathbf{r}_{P/cm}$ = position of P relative to CM\n",
        "\n",
        "**Angular Equation of Motion** (about CM or fixed axis):\n",
        "$$\\sum \\tau = I \\alpha$$\n",
        "\n",
        "where:\n",
        "- $\\tau$ = torque (N·m)\n",
        "- $I$ = moment of inertia (kg·m²) — **resistance to rotation**\n",
        "- $\\alpha = \\dot{\\omega}$ = angular acceleration (rad/s²)\n",
        "\n",
        "### Moment of Inertia\n",
        "**Definition**: How mass is distributed about rotation axis\n",
        "$$I = \\int r^2 \\, dm = \\sum m_i r_i^2$$\n",
        "\n",
        "**Common Shapes** (about center):\n",
        "- **Point mass**: $I = m r^2$\n",
        "- **Thin rod** (length L, mass m, about center): $I = \\frac{1}{12} m L^2$\n",
        "- **Solid disk/cylinder** (radius R): $I = \\frac{1}{2} m R^2$\n",
        "- **Hollow cylinder** (radius R): $I = m R^2$\n",
        "- **Solid sphere**: $I = \\frac{2}{5} m R^2$\n",
        "\n",
        "**Parallel Axis Theorem**: Shift axis from CM to distance $d$ away\n",
        "$$I_{\\text{new}} = I_{cm} + m d^2$$\n",
        "\n",
        "### Combined Motion: Rolling\n",
        "**Rolling without slipping**: Point at contact has zero velocity!\n",
        "$$v_{cm} = \\omega R \\quad \\text{(constraint)}$$\n",
        "\n",
        "**Consequences**:\n",
        "- Acceleration: $a_{cm} = \\alpha R$\n",
        "- Total kinetic energy: $KE = \\frac{1}{2} m v_{cm}^2 + \\frac{1}{2} I_{cm} \\omega^2$\n",
        "\n",
        "---\n"
    ]
})

